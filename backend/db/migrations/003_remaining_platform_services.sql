CREATE TABLE IF NOT EXISTS cart_items (
  id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, book_id CHAR(36) NOT NULL,
  quantity INT NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_cart_user_book(user_id,book_id)
);
CREATE TABLE IF NOT EXISTS book_reviews (
  id CHAR(36) PRIMARY KEY, book_id CHAR(36) NOT NULL, user_id CHAR(36) NOT NULL,
  rating TINYINT NOT NULL, comment TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_review_user_book(user_id,book_id)
);
CREATE TABLE IF NOT EXISTS refunds (
  id CHAR(36) PRIMARY KEY, payment_order_id CHAR(36) NOT NULL, amount DECIMAL(10,2) NOT NULL,
  reason TEXT, status ENUM('PENDING','SUCCESS','FAILED') DEFAULT 'PENDING',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
ALTER TABLE session_answers ADD UNIQUE KEY uq_session_question(session_id,question_id);
ALTER TABLE exam_sessions ADD COLUMN last_heartbeat_at TIMESTAMP NULL;
CREATE TABLE IF NOT EXISTS exam_integrity_events (
  id CHAR(36) PRIMARY KEY, session_id CHAR(36) NOT NULL, event_type VARCHAR(100) NOT NULL,
  metadata JSON, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_integrity_session(session_id)
);
CREATE TABLE IF NOT EXISTS notifications (
  id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, type VARCHAR(100) NOT NULL,
  subject VARCHAR(255), body TEXT NOT NULL, status VARCHAR(50) DEFAULT 'DELIVERED',
  read_at TIMESTAMP NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_notifications_user(user_id)
);
CREATE TABLE IF NOT EXISTS notification_jobs (
  id CHAR(36) PRIMARY KEY, user_id CHAR(36), channel VARCHAR(30) NOT NULL,
  template_key VARCHAR(100) NOT NULL, payload JSON, status ENUM('QUEUED','PROCESSING','SENT','FAILED') DEFAULT 'QUEUED',
  attempts INT DEFAULT 0, processed_at TIMESTAMP NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_notification_jobs_status(status,created_at)
);
CREATE TABLE IF NOT EXISTS files (
  id CHAR(36) PRIMARY KEY, owner_id CHAR(36) NOT NULL, storage_key VARCHAR(1000) NOT NULL,
  file_name VARCHAR(255) NOT NULL, content_type VARCHAR(150), size_bytes BIGINT DEFAULT 0,
  status ENUM('PENDING','READY','DELETED') DEFAULT 'PENDING', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, INDEX idx_files_owner(owner_id)
);
CREATE TABLE IF NOT EXISTS report_jobs (
  id CHAR(36) PRIMARY KEY, type VARCHAR(100) NOT NULL, filters JSON,
  status ENUM('QUEUED','PROCESSING','COMPLETED','FAILED') DEFAULT 'QUEUED',
  output_url VARCHAR(1000), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
