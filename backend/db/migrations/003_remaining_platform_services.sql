CREATE TABLE IF NOT EXISTS admin_roles (
  id CHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE, description TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS role_permissions (
  role_id CHAR(36) NOT NULL, permission_key VARCHAR(150) NOT NULL,
  PRIMARY KEY(role_id, permission_key)
);
CREATE TABLE IF NOT EXISTS admin_staff (
  id CHAR(36) PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL, status ENUM('ACTIVE','INACTIVE','SUSPENDED') DEFAULT 'ACTIVE',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admin_staff_roles (
  staff_id CHAR(36) NOT NULL, role_id CHAR(36) NOT NULL, PRIMARY KEY(staff_id,role_id)
);
CREATE TABLE IF NOT EXISTS audit_logs (
  id CHAR(36) PRIMARY KEY, actor_id CHAR(36), action VARCHAR(255) NOT NULL,
  entity_type VARCHAR(100), entity_id CHAR(36), ip_address VARCHAR(45), metadata JSON,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_audit_actor(actor_id), INDEX idx_audit_created(created_at)
);
CREATE TABLE IF NOT EXISTS system_settings (
  setting_key VARCHAR(150) PRIMARY KEY, setting_value JSON NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS offers (
  id CHAR(36) PRIMARY KEY, title VARCHAR(255) NOT NULL, description TEXT, code VARCHAR(100),
  starts_at TIMESTAMP NULL, ends_at TIMESTAMP NULL, is_active TINYINT(1) DEFAULT 1,
  display_order INT DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS faqs (
  id CHAR(36) PRIMARY KEY, question TEXT NOT NULL, answer TEXT NOT NULL,
  is_active TINYINT(1) DEFAULT 1, display_order INT DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
